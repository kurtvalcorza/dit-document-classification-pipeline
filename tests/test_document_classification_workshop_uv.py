# ---- kernel <-> stage hand-off with a model double --------------------------------------------------------
def _kernel_predict(tmp_path, monkeypatch):
    """The notebook's batched_predict, wired in-process to the stage file with a model double."""
    scored = []

    def double(_processor, _model, records, batch_size):
        scored.append([r["image"].size for r in records])
        scores = np.full((len(records), 16), 0.2 / 15, dtype=np.float32)
        scores[:, 4] = 0.8
        return np.log(scores), scores, [0.0] * -(-len(records) // batch_size), None

    monkeypatch.setattr(stages, "load_converted_model", lambda: (None, None, 0.0))
    monkeypatch.setattr(stages, "batched_predict", double)
    monkeypatch.setattr(stages, "device", lambda: "cpu")
    stage_calls = []

    def run_stage(stage, *options, **_settings):
        stage_calls.append((stage, options))
        assert stage == "predict" and options[0] == "--job"
        stages.stage_predict(options[1])

    tree = ast.parse(_src("b485b2eb"))
    tree.body = [node for node in tree.body if isinstance(node, ast.FunctionDef)
                 and node.name in {"batched_predict", "rank_classes"}]
    ns = {"Path": Path, "Image": Image, "np": np, "json": json, "tempfile": __import__("tempfile"),
          "WORK_ROOT": tmp_path / "work", "BATCH_SIZE": 16, "run_stage": run_stage,
          "read_json": lambda path: json.loads(Path(path).read_text(encoding="utf-8"))}
    exec(compile(tree, "b485b2eb", "exec"), ns)
    return ns, scored, stage_calls


def test_kernel_batched_predict_round_trips_pages_through_the_stage(tmp_path, monkeypatch):
    ns, scored, stage_calls = _kernel_predict(tmp_path, monkeypatch)
    page = tmp_path / "page.png"
    Image.new("RGB", (60, 80), "white").save(page)
    records = [{"image_id": "a", "png": str(page), "image": Image.open(page).convert("RGB")},
               {"image_id": "b", "image": Image.new("RGB", (50, 70), "black")}]
    logits, scores, timings, peak = ns["batched_predict"](records, batch_size=1)
    assert len(stage_calls) == 1 and scored == [[(60, 80), (50, 70)]]
    assert scores.shape == (2, 16) and logits.shape == (2, 16) and timings == [0.0, 0.0] and peak is None
    assert ns["rank_classes"](scores)[:, 0].tolist() == [4, 4]


@pytest.mark.parametrize("variant", stages.ROBUSTNESS_VARIANTS)
def test_variants_are_made_in_the_stage_and_returned_for_display(tmp_path, monkeypatch, variant):
    ns, scored, _calls = _kernel_predict(tmp_path, monkeypatch)
    page = tmp_path / "page.png"
    base = Image.new("RGB", (60, 80), "white")
    base.putpixel((0, 0), (10, 20, 30))
    base.save(page)
    record = {"image_id": "a", "png": str(page), "image": base, "variant": variant}
    ns["batched_predict"]([record], batch_size=16)
    expected = stages.transform_variant(base, variant)
    assert scored == [[expected.size]]
    assert record["image"].size == expected.size and record["image"].tobytes() == expected.tobytes()


