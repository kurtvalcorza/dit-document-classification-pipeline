def test_sample_selection_is_the_seeded_per_class_ranking():
    labels = [i % 16 for i in range(16 * 30)]
    chosen = stages.select_sample_indices(labels, 42, 20)
    assert len(chosen) == 320 and chosen == sorted(chosen)
    for label_id in range(16):
        rows = [i for i in range(len(labels)) if labels[i] == label_id]
        ranked = sorted(rows, key=lambda i: hashlib.sha256(f"42:{i}:{label_id}".encode()).hexdigest())
        assert sorted(ranked[:20]) == [i for i in chosen if labels[i] == label_id]
    with pytest.raises(RuntimeError, match="has only"):
        stages.select_sample_indices(labels[:16 * 19], 42, 20)


def test_stage_command_line_rejects_unknown_stages_and_a_predict_without_a_job(tmp_path):
    config = tmp_path / "config.json"
    config.write_text(json.dumps({"work_dir": str(tmp_path / "work")}), encoding="utf-8")
    command = [sys.executable, str(STAGE_FILE), "--config", str(config), "--stage"]
    unknown = subprocess.run([*command, "train"], capture_output=True, text=True, timeout=60)
    assert unknown.returncode == 2 and "invalid choice" in unknown.stderr
    no_job = subprocess.run([*command, "predict"], capture_output=True, text=True, timeout=60)
    assert no_job.returncode == 2 and "--job is required" in no_job.stderr
